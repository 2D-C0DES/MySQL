(
    JOB_ID VARCHAR2(20),
    JOB_TITLE VARCHAR2(50),
    MIN_SALARY NUMBER(10),
    MAX_SALARY NUMBER(10)
);

CREATE TABLE EMPLOYEES
(
    EMPLOYEE_ID NUMBER(5),
    FIRST_NAME VARCHAR2(50),
    LAST_NAME VARCHAR2(50),
    JOB_ID VARCHAR2(20),
    MANAGER_ID NUMBER(5),
    HIRE_DATE DATE,
    SALARY NUMBER(10,2),
    COMMISSION_PCT NUMBER(5,2),
    DEPARTMENT_ID NUMBER(5)
);



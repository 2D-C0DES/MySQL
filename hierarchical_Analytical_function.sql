SELECT
CONCAT(LPAD(' ',LEVEL*3-3), first_name) AS employee_hierarchy
FROM employees
CONNECT BY PRIOR employee_id = manager_id
START WITH manager_id IS NULL;


SELECT
first_name,
LEVEL,
manager_id,
CONNECT_BY_ROOT first_name AS top_boss
FROM employees
CONNECT BY PRIOR employee_id = manager_id
START WITH manager_id IS NULL;


